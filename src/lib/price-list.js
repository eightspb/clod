export function groupPriceItemsBySection(items = []) {
  return items.reduce((groups, item) => {
    const title = item.section ?? 'Услуги'
    const existingGroup = groups[groups.length - 1]

    if (!existingGroup || existingGroup.title !== title) {
      groups.push({ title, items: [item] })
      return groups
    }

    existingGroup.items.push(item)
    return groups
  }, [])
}

function buildSchemaItems(categories) {
  let position = 1

  return categories.flatMap((category) =>
    category.items.map((item) => ({
      '@type': 'ListItem',
      position: position++,
      item: {
        '@type': 'MedicalProcedure',
        name: item.name ?? item.title,
        description: `${category.title}. ${item.price === 0 ? 'Стоимость обсуждается индивидуально.' : `Стоимость ${formatPriceLabel(item.price, item.isFrom)}.`}`,
        offers: {
          '@type': 'Offer',
          price: String(item.price),
          priceCurrency: 'RUB',
          seller: { '@type': 'MedicalBusiness', name: 'Клиника Одинцова' },
        },
      },
    }))
  )
}

