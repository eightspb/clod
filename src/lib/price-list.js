function getOfficialItem(code) {
  const item = FULL_PRICE_ITEM_MAP.get(code)

  if (!item) {
    throw new Error(`Unknown official price item code: ${code}`)
  }

  return item
}

function pickOfficialItems(selections) {
  return selections.map(({ code, name, isFrom = false, description }) => {
    const item = getOfficialItem(code)

    return {
      code,
      name: name ?? item.title,
      price: item.price,
      isFrom,
      description,
    }
  })
}

